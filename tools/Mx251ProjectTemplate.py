"""StudioX project scaffold; compiler defaults belong to the installed toolchain."""


def render(ai8051u: bool) -> str:
    text = '''cmake_minimum_required(VERSION 3.25)

# 器件与工具链设置由 device 目录提供。
include("${CMAKE_CURRENT_SOURCE_DIR}/device/platform.cmake")
project(mx251_firmware_project LANGUAGES NONE)

add_library(app INTERFACE)

# 1. 用户源码：每行一个文件。
target_sources(app INTERFACE
    src/main.c
)

# 2. 用户头文件目录。
target_include_directories(app INTERFACE
    include
)

# 3. 用户宏：填写宏名或 宏名=值，不需要 -D。
target_compile_definitions(app INTERFACE
    # USE_UART=1
)

'''
    if ai8051u:
        text += '''# 4. 使用库函数模板时，在这里选择所需驱动与系统时钟。
set(STC_CLOCK_HZ 40000000 CACHE STRING "System clock (Hz)")
set(STC_COMPONENTS GPIO)

'''
    return text + '''# 生成固件；内存模型、优化方式和 C 标准在 mx251.json 中设置。
studiox_configure_firmware(app)
'''


def platform(ai8051u: bool) -> str:
    text = '''# Generated by StudioX. 器件构建入口；用户配置位于工程根目录。
include_guard(GLOBAL)
include("${MX251_PROJECT_MODULE}")

function(studiox_configure_firmware target)
'''
    if ai8051u:
        text += '''    if(EXISTS "${CMAKE_SOURCE_DIR}/include/library_config.h")
        include("${CMAKE_CURRENT_FUNCTION_LIST_DIR}/sdk/stc/cmake/MX251StcSdk.cmake")
        mx251_stc_sdk(${target}
            TARGET AI8051U-34K64-32
            CLOCK_HZ "${STC_CLOCK_HZ}"
            COMPONENTS ${STC_COMPONENTS}
        )
        mx251_stc_firmware(${target})
    else()
        mx251_firmware(${target})
    endif()
'''
    else:
        text += '    mx251_firmware(${target})\n'
    return text + 'endfunction()\n'
